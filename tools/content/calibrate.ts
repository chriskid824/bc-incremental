/**
 * The calibration tool (docs/v3 C6 design D26, §4.10, §4.11; B-1, S-1, F21; the lead's rulings
 * R3 and R4): calibrateFusion in-process, one fusion after another, then
 * src/data/fusion/calibrated.ts rewritten when its text changes, sorted by key under its
 * generated-file header.
 *
 *   npm run calibrate -- [--stale | --all | --only <key>] [--seeds 8]
 *
 * The fusions are those of every registered character with a center, in FULL_SCOPE, which
 * assembles every fusion and has no wave cap, with a fresh save's account; an entry is per fusion
 * key, whatever scope reads it (R3). --stale, the default, calibrates the fusions with no entry or
 * a stale digest, --all every one, --only one. Each fusion prints its key, kind, coef, status,
 * median, min, max and range, with its runs, timeouts and wall time; the run exits 1 when a status
 * it measured is not ok and the key has no ACCEPTED_FAILS reason, so a PR that touches a fusion
 * shows its FAIL (F21). Before B1 no registered character has a center: it calibrates nothing,
 * says so, and leaves the table as it is (R4).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { characterGameData } from '../../src/data';
import { CHARACTER_IDS } from '../../src/data/sources';
import { assembleWeb, FULL_SCOPE, loadContent } from '../../src/data/web';
import type { CalibrationEntry, Content, FusionKey } from '../../src/data/web';
import { CALIBRATION_SEEDS, calibrateFusion } from '../../src/meta/web/calibrate';
import type { CalibrationResult } from '../../src/meta/web/calibrate';

export type CalibrationTable = Readonly<Partial<Record<FusionKey, CalibrationEntry>>>;

export const CALIBRATED_FILE = new URL('../../src/data/fusion/calibrated.ts', import.meta.url);

/** The entry's fields in the order CalibrationEntry declares them. */
const FIELDS: readonly (keyof CalibrationEntry)[] = [
  'coef',
  'status',
  'median',
  'min',
  'max',
  'seeds',
  'startWave',
  'digest',
];

/** The generated-file header; C6.4's, with its last sentence while the table is empty (R4). */
function header(empty: boolean): string[] {
  const last = ' * what it was calibrated for, sorted by key (docs/v3 C6 design D26, §4.10).';
  return [
    '/**',
    ' * Generated by `npm run calibrate` (tools/content/calibrate.ts); do not edit by hand. Each',
    " * fusion's calibrated coefficient with its status, its paired strength readings and the digest of",
    ...(empty ? [`${last} Empty until B1's`, ' * fusions are calibrated.'] : [last]),
    ' */',
  ];
}

const literal = (value: string | number): string =>
  typeof value === 'number' ? String(value) : `'${value}'`;

/**
 * The text of src/data/fusion/calibrated.ts for `entries`: sorted by key, each entry's fields in
 * CalibrationEntry's order, laid out as Prettier leaves it.
 */
export function calibratedSource(entries: CalibrationTable): string {
  const keys = (Object.keys(entries) as FusionKey[]).sort();
  const body = keys.flatMap((key) => {
    const entry = entries[key] as CalibrationEntry;
    return [
      `  '${key}': {`,
      ...FIELDS.map((field) => `    ${field}: ${literal(entry[field])},`),
      '  },',
    ];
  });
  const open =
    'export const CALIBRATED: Readonly<Partial<Record<FusionKey, CalibrationEntry>>> = {';
  return [
    ...header(keys.length === 0),
    '',
    "import type { CalibrationEntry, FusionKey } from '../web/types';",
    '',
    ...(keys.length === 0 ? [`${open}};`] : [open, ...body, '};']),
    '',
  ].join('\n');
}

/** Each fusion's digest in FULL_SCOPE, for every registered character with a center (R3). */
export function fusionDigests(content: Content): Map<FusionKey, string> {
  const digests = new Map<FusionKey, string>();
  for (const c of CHARACTER_IDS) {
    if (content.characters[c].center === null) continue;
    for (const fusion of assembleWeb(content, c, FULL_SCOPE).fusions.values()) {
      digests.set(fusion.key, fusion.digest);
    }
  }
  return digests;
}

/** The keys a run calibrates, sorted: every fusion, or those with no entry or a stale digest. */
export function keysToCalibrate(content: Content, mode: 'stale' | 'all'): FusionKey[] {
  return [...fusionDigests(content)]
    .filter(([key, digest]) => mode === 'all' || content.calibrated[key]?.digest !== digest)
    .map(([key]) => key)
    .sort();
}

/** A fusion's line: key, kind, coef, status, median, min, max and range, then its cost. */
export function resultLine(result: CalibrationResult, seconds: number): string {
  const { entry, range } = result;
  return (
    `${result.key} (${result.kind}): coef ${entry.coef}, ${entry.status}, median ` +
    `${entry.median}, min ${entry.min}, max ${entry.max}, range ` +
    `${range === null ? 'none' : `${range[0]}–${range[1]}`}; ${result.runs} runs, ` +
    `${result.timeouts} timeouts, ${result.ticks} ticks, ${seconds.toFixed(1)} s`
  );
}

function main(): void {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    strict: true,
    options: {
      stale: { type: 'boolean', default: false },
      all: { type: 'boolean', default: false },
      only: { type: 'string' },
      seeds: { type: 'string' },
    },
  });
  const modes = [values.stale, values.all, values.only !== undefined].filter(Boolean).length;
  if (modes > 1) throw new Error('npm run calibrate: give one of --stale, --all and --only');
  const seeds = values.seeds === undefined ? CALIBRATION_SEEDS : Number(values.seeds);
  if (!Number.isInteger(seeds) || seeds < 1) {
    throw new Error(`--seeds must be an integer >= 1, got '${values.seeds ?? ''}'`);
  }
  const content = loadContent();
  const digests = fusionDigests(content);
  const only = values.only as FusionKey | undefined;
  if (only !== undefined && !digests.has(only)) {
    throw new Error(
      `npm run calibrate: --only '${only}' names no fusion of a registered character's web`,
    );
  }
  const keys = only === undefined ? keysToCalibrate(content, values.all ? 'all' : 'stale') : [only];
  if (digests.size === 0) {
    console.log(
      "npm run calibrate: no registered character has a center yet (B1 writes 熔核's), so no " +
        'fusion is calibrated',
    );
  } else if (keys.length === 0) {
    console.log(
      'npm run calibrate: every entry is fresh, so no fusion is calibrated (--all redoes each)',
    );
  }
  const data = characterGameData();
  const entries: Partial<Record<FusionKey, CalibrationEntry>> = { ...content.calibrated };
  const failed: FusionKey[] = [];
  for (const key of keys) {
    const started = performance.now();
    const result = calibrateFusion(content, key, data, { seeds });
    console.log(resultLine(result, (performance.now() - started) / 1000));
    entries[key] = result.entry;
    if (result.entry.status !== 'ok' && (content.acceptedFails[key] ?? '').trim() === '') {
      failed.push(key);
    }
  }
  const text = calibratedSource(entries);
  const changed = readFileSync(CALIBRATED_FILE, 'utf8') !== text;
  if (changed) writeFileSync(CALIBRATED_FILE, text);
  const count = Object.keys(entries).length;
  console.log(
    `wrote src/data/fusion/calibrated.ts (${changed ? 'changed' : 'unchanged'}): ` +
      `${count} ${count === 1 ? 'entry' : 'entries'}, ${keys.length} calibrated now`,
  );
  if (failed.length > 0) {
    console.log(
      `npm run calibrate FAILED: ${failed.join(', ')} not ok, with no ACCEPTED_FAILS reason ` +
        '(src/data/fusion/overrides.ts); rework the fusion or give the reason',
    );
    process.exitCode = 1;
  }
}

const entry = process.argv[1];
if (entry !== undefined && import.meta.url === pathToFileURL(entry).href) main();
